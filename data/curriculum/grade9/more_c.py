def mcq(diff, zh, en, answer, ez, ee, options, marks=1):
    return dict(type="mcq", difficulty=diff, stem_zh=zh, stem_en=en, answer=answer, exp_zh=ez, exp_en=ee, options=options, marks=marks)

def shortq(diff, zh, en, answer, ez, ee, accepted, marks=1):
    return dict(type="short", difficulty=diff, stem_zh=zh, stem_en=en, answer=answer, exp_zh=ez, exp_en=ee, accepted=accepted, marks=marks)

def numq(diff, zh, en, answer, ez, ee, marks=1, tolerance=0, accepted=None):
    q = dict(type="numeric", difficulty=diff, stem_zh=zh, stem_en=en, answer=str(answer), exp_zh=ez, exp_en=ee, marks=marks, tolerance=tolerance)
    if accepted:
        q["accepted"] = accepted
    return q

