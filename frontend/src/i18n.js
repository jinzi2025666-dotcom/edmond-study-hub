export function tr(lang, key, vars) {
  const table = strings[lang] || strings.en;
  let text = table[key] || strings.en[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replaceAll(`{${k}}`, String(v));
    });
  }
  return text;
}
